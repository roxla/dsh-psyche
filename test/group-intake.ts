import { mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { openDatabase } from '../packages/core/dist/adapter.js'
import { Core } from '../packages/core/dist/store.js'
import { loadGrowthInputs } from '../packages/core/dist/growth.js'
import { generateDiary } from '../packages/core/dist/diary-generation.js'

let passed=0,failed=0
function eq(label,actual,expected) { if(JSON.stringify(actual)===JSON.stringify(expected)){passed++;console.log('  ok '+label)}else{failed++;console.error('  FAIL '+label, {actual,expected})} }
const log={info(){},debug(){},warn(){},error(){}}
const dir=mkdtempSync(join(tmpdir(),'psyche-group-intake-'))
const file=join(dir,'memory.sqlite3')
const {db}=await openDatabase({file,logger:log})
const core=new Core({db,config:{},logger:log,dataDir:dir})
const count=(table)=>Number(db.get(`SELECT COUNT(*) AS n FROM ${table}`).n)
const T='2026-11-13T04:00:00.000Z'
const input=(messageId,overrides={})=>({externalRoomId:'41001',stableUserId:'31001',messageId,selfId:'39999',mentions:[],text:'UNRETAINED-PRIVATE-CONTENT',captureMode:'mentioned_only',at:T,...overrides})
async function rejects(label,fn) {let rejected=false;try{await fn()}catch{rejected=true}eq(label,rejected,true)}
const growthBefore=loadGrowthInputs(db)
const first=await core.ingestGroupMessage(input('ordinary'))
eq('普通消息序号1',first.roomSeq,1)
eq('普通消息不保留正文',first.retained,false)
eq('普通消息无Source/Event',[first.sourceId,first.eventId,count('sources'),count('events')],[null,null,0,0])
eq('内部Room与外部群号不同',first.roomId==='41001',false)
eq('成员只记录观察',count('room_members'),1)
eq('普通正文不进operations',JSON.stringify(db.all('SELECT result,error FROM operations')).includes('UNRETAINED-PRIVATE-CONTENT'),false)
const mentioned=await core.ingestGroupMessage(input('mentioned',{mentions:['39999'],text:'GROUP-SELECTED-BODY'}))
eq('明确叫到保留Source/Event',[mentioned.roomSeq,mentioned.retained,!!mentioned.sourceId,!!mentioned.eventId],[2,true,true,true])
const source=db.get('SELECT * FROM sources WHERE source_id=?',[mentioned.sourceId])
eq('Source归属正确',[source.platform,source.channel,source.room_id,source.message_id,source.text],['qq','group',first.roomId,'mentioned','GROUP-SELECTED-BODY'])
eq('Event复用同一证据链',db.get('SELECT COUNT(*) AS n FROM event_sources WHERE event_id=? AND source_id=?',[mentioned.eventId,mentioned.sourceId]).n,1)
eq('Event不复制原正文',db.get('SELECT text FROM events WHERE event_id=?',[mentioned.eventId]).text.includes('GROUP-SELECTED-BODY'),false)
const replay=await core.ingestGroupMessage(input('mentioned',{mentions:['39999'],text:'GROUP-SELECTED-BODY'}))
eq('重复消息重放同一来源',[replay.replayed,replay.sourceId,replay.roomSeq],[true,mentioned.sourceId,2])
eq('重复投递不重复Source/Event',[count('sources'),count('events'),count('room_message_seq')],[1,1,2])
await rejects('同一保留消息改正文拒绝',()=>core.ingestGroupMessage(input('mentioned',{text:'changed'})))
await rejects('同一保留消息换发送者拒绝',()=>core.ingestGroupMessage(input('mentioned',{stableUserId:'31002',text:'GROUP-SELECTED-BODY'})))
const omittedReplay=await core.ingestGroupMessage(input('ordinary',{mentions:['39999'],text:'CHANGED-BUT-STILL-OMITTED',captureMode:'all_visible_messages'}))
eq('去重不把旧未保留消息升级为正文',[omittedReplay.retained,omittedReplay.roomSeq,count('sources')],[false,1,1])
const other=await core.ingestGroupMessage(input('ordinary',{externalRoomId:'41002'}))
eq('不同群同消息ID独立编号',[other.roomId!==first.roomId,other.roomSeq],[true,1])
const all=await core.ingestGroupMessage(input('all',{captureMode:'all_visible_messages',text:'ALL-VISIBLE'}))
eq('all模式保留普通消息',[all.retained,all.roomSeq],[true,3])
const telegram=await core.resolveContact({platform:'telegram',stableUserId:'31001',channel:'group',externalRoomId:'41001'})
eq('同外部群号不同平台不合并',db.get("SELECT room_id FROM rooms WHERE platform='telegram' AND external_room_id='41001'").room_id!==first.roomId,true)
eq('跨平台Contact不合并',telegram.contactId!==source.sender_contact_id,true)
await core.capture({platform:'qq',channel:'group',roomId:first.roomId,messageId:'self-msg',origin:'self',text:'SELF-REPLY',at:T})
const quoted=await core.ingestGroupMessage(input('quote',{replyToMessageId:'self-msg',text:'QUOTE-REPLY'}))
eq('同Room真实self回复可选择',quoted.retained,true)
const foreignQuote=await core.ingestGroupMessage(input('foreign-quote',{externalRoomId:'41002',replyToMessageId:'self-msg'}))
eq('他群self消息不能选择正文',foreignQuote.retained,false)
const beforeAtomic=[count('sources'),count('events'),count('room_message_seq'),db.get('SELECT last_seq FROM room_participation_state WHERE room_id=?',[first.roomId]).last_seq]
db.exec("CREATE TRIGGER intake_test_abort BEFORE INSERT ON room_message_seq WHEN NEW.message_id='abort' BEGIN SELECT RAISE(ABORT,'fixture failure'); END")
await rejects('映射写失败整笔回滚',()=>core.ingestGroupMessage(input('abort',{mentions:['39999'],text:'MUST-ROLL-BACK'})))
eq('Source/Event/序号无半批',[count('sources'),count('events'),count('room_message_seq'),db.get('SELECT last_seq FROM room_participation_state WHERE room_id=?',[first.roomId]).last_seq],beforeAtomic)
db.exec('DROP TRIGGER intake_test_abort')
db.run('UPDATE rooms SET active=0 WHERE room_id=?',[first.roomId])
await rejects('停用Room拒绝接入',()=>core.ingestGroupMessage(input('inactive')))
eq('配置不能自动复活Room',db.get('SELECT active FROM rooms WHERE room_id=?',[first.roomId]).active,0)
db.run('UPDATE rooms SET active=1 WHERE room_id=?',[first.roomId])
await rejects('非法身份拒绝',()=>core.ingestGroupMessage(input('bad',{externalRoomId:'*'})))
await rejects('缺失消息ID拒绝',()=>core.ingestGroupMessage(input('')))
await rejects('非法采集模式拒绝',()=>core.ingestGroupMessage(input('badmode',{captureMode:'anything'})))
eq('水位只初始化不推进',db.get('SELECT read_through_seq,participation_state FROM room_participation_state WHERE room_id=?',[first.roomId]),{read_through_seq:0,participation_state:'idle'})
const readBefore=count('operations')
core.readGroupIntake(first.roomId)
eq('内部只读快照不审计写入',count('operations'),readBefore)
await rejects('未知Room快照拒绝',()=>core.readGroupIntake('41001'))
await rejects('映射不可改',()=>db.run('UPDATE room_message_seq SET message_id=? WHERE room_id=? AND room_seq=1',['changed',first.roomId]))
await rejects('映射不可删',()=>db.run('DELETE FROM room_message_seq WHERE room_id=?',[first.roomId]))
await rejects('证据不能串群',()=>db.run('INSERT INTO room_message_seq(room_id,platform,message_id,room_seq,source_id,received_at) VALUES (?,?,?,?,?,?)',[other.roomId,'qq','wrong-evidence',99,source.source_id,T]))
db.run('UPDATE room_participation_state SET read_through_seq=1 WHERE room_id=?',[first.roomId])
await rejects('水位不能回退',()=>db.run('UPDATE room_participation_state SET read_through_seq=0 WHERE room_id=?',[first.roomId]))
await rejects('水位不能越过接入序号',()=>db.run('UPDATE room_participation_state SET read_through_seq=999 WHERE room_id=?',[first.roomId]))
eq('群采集不改变Growth输入',loadGrowthInputs(db),growthBefore)
const diary=await generateDiary(db,{scope:{},date:'2026-11-13',now:new Date('2026-11-13T12:00:00.000Z')})
eq('群采集不进入默认日记',diary.skipped,'no-content')
eq('不自动晋升/写Mood/关系',[count('artifacts'),count('mood_meta'),count('relationship_signals')],[0,0,0])
const snapshot=core.readGroupIntake(first.roomId)
db.close()
const reopened=await openDatabase({file,logger:log})
const again=new Core({db:reopened.db,config:{},logger:log,dataDir:dir})
eq('重启序号/水位/去重持久化',again.readGroupIntake(first.roomId),snapshot)
eq('重启不重复保留Source',(await again.ingestGroupMessage(input('mentioned',{mentions:['39999'],text:'GROUP-SELECTED-BODY'}))).sourceId,mentioned.sourceId)
reopened.db.close()
console.log(`[P4-D-1 group-intake] ${passed} 通过 ${failed} 失败`)
if(failed)process.exitCode=1
